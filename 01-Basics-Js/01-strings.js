// Js Strings Method ;

let anotherName = "sarhan";

// Repeat Method :
console.log(anotherName.repeat(2));

// PadEnd Method :
console.log(anotherName.padEnd(11, "noe"));

// PadStart Method
console.log(anotherName.padStart(10, "noe"));

// At Method :
console.log(anotherName.at(1));

// ReplaceAl Method :
console.log(anotherName.replaceAll("https.com", "htppsishis.aouhai"));

// Replace Method :
console.log(anotherName.replace("https", "nowppt"));

// EndsWith Method :
console.log(anotherName.endsWith("com"));

// Trim Method :
console.log(anotherName.trim());

// Includes Method :
console.log(anotherName.includes("sarhan"));

// Length Check Method :
console.log(anotherName.length);

// Slice Method :
console.log(anotherName.slice(0, 5));

// Split Method :
console.log(anotherName.split(","));

// To Lower Case Method :
console.log(anotherName.toLowerCase);

// To upperCase Method :
console.log(anotherName.toUpperCase);
